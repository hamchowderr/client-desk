// Bundles each MCP Apps view into one self-contained HTML string module that the
// MCP server serves under ui://. Views must not load anything from the network.
import { build } from 'esbuild'
import { readdir, readFile, writeFile } from 'node:fs/promises'

const views = ['desk']

for (const name of views) {
  const out = await build({
    entryPoints: [`src/apps/${name}.ts`],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    write: false,
  })
  const js = out.outputFiles[0].text.replace(/<\/script/gi, '<\\/script')
  const shell = await readFile(`src/apps/${name}.html`, 'utf8')
  const html = shell.replace('/*APP_JS*/', () => js)
  await writeFile(
    `src/apps/${name}.generated.ts`,
    `// Generated by scripts/build-apps.mjs. Do not edit.\nexport default ${JSON.stringify(html)}\n`,
  )
  console.log(`built ${name} view (${(html.length / 1024).toFixed(1)} KB)`)
}

// Skills ship two ways: as files in the Claude plugin (plugin/skills, Chowderr's
// own) and as skill:// resources on the MCP servers (SEP-2640 draft). Client-agent
// skills live in skills/ so they never load into the owner's Claude.
const skills = {}
for (const root of ['plugin/skills', 'skills']) {
  for (const dir of await readdir(root)) {
    skills[dir] = await readFile(`${root}/${dir}/SKILL.md`, 'utf8')
  }
}
await writeFile(
  'src/skills.generated.ts',
  `// Generated by scripts/build-apps.mjs from plugin/skills and skills/. Do not edit.\nexport default ${JSON.stringify(skills, null, 2)} as Record<string, string>\n`,
)
console.log(`bundled ${Object.keys(skills).length} skills`)
